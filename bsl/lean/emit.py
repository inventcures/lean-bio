"""BSL -> Lean 4 semantics.

Emits the denotational semantics of a mass-action model:

  * an inductive `Species`,
  * a `Params` structure with an interval-bound `Params.Valid` predicate
    (the confidence-graded assumptions from the BSL source),
  * the mass-action vector field `dXdt`, and
  * one theorem per declared invariant asserting d/dt(invariant) = 0.

The conservation theorems are real and, for genuine conservation laws, close by
`simp only [dXdt]; ring`. This module emits the Lean text; running Lean to
*discharge* the proofs (the kernel check) is the next milestone. The output
requires a Lean 4 toolchain with Mathlib.
"""

from __future__ import annotations

from ..nodes import Model, Reaction, exact
from .names import user, internal, comment

P = internal("p")   # parameter-record binder
X = internal("x")   # state binder


def _fmt(v: float) -> str:
    # Exact rational literal: `repr(float)` would print `1e-09` (not Lean
    # syntax) or `inf`, and a float is only an approximation of the source.
    q = exact(v)
    if q.denominator == 1:
        return str(q.numerator)
    return f"({q.numerator} / {q.denominator} : ℝ)"


def _argref(a) -> str:
    return f"{P}.{user(a.name)}" if a.name is not None else _fmt(a.value)


def _flux(r: Reaction) -> str:
    if r.rate_law == "mass_action":
        parts = [_argref(r.rate_args[0])]
        for ref in r.reactants:
            if ref.coeff == 1.0:
                parts.append(f"{X} {user(ref.species)}")
            else:
                parts.append(f"{X} {user(ref.species)} ^ {_fmt(ref.coeff)}")
        return " * ".join(parts)
    if r.rate_law == "michaelis_menten":
        vmax = _argref(r.rate_args[0])
        km = _argref(r.rate_args[1])
        s = f"{X} {user(r.reactants[0].species)}"
        return f"{vmax} * {s} / ({km} + {s})"
    if r.rate_law == "hill":
        vmax = _argref(r.rate_args[0])
        km = _argref(r.rate_args[1])
        n = _argref(r.rate_args[2])
        s = f"{X} {user(r.reactants[0].species)}"
        return f"{vmax} * {s} ^ {n} / ({km} ^ {n} + {s} ^ {n})"
    return "0"


def _net(r: Reaction, species: str):
    """Exact net stoichiometric coefficient (a `Fraction`)."""
    produced = sum(exact(ref.coeff) for ref in r.products if ref.species == species)
    consumed = sum(exact(ref.coeff) for ref in r.reactants if ref.species == species)
    return produced - consumed


def _dxdt_rhs(model: Model, species: str) -> str:
    terms: list[tuple[str, str]] = []  # (sign, magnitude-expr)
    for r in model.reactions:
        c = _net(r, species)
        if c == 0:
            continue
        flux = _flux(r)
        mag = f"({flux})" if abs(c) == 1.0 else f"{_fmt(abs(c))} * ({flux})"
        terms.append(("+" if c > 0 else "-", mag))
    if not terms:
        return "0"
    sign0, mag0 = terms[0]
    out = mag0 if sign0 == "+" else f"-{mag0}"
    for sign, mag in terms[1:]:
        out += f" {sign} {mag}"
    return out


def emit_lean(model: Model) -> str:
    L: list[str] = []
    sp = [user(s.name) for s in model.species]
    ns = f"BSL.{user(model.name)}"

    L.append(f"/- Auto-generated by GSK-LeanBio from {comment(model.source.name)}. -/")
    L.append(f"/- Model: {comment(model.name)}. Do not edit by hand. -/")
    L.append("import Mathlib")
    L.append("")
    L.append(f"namespace {ns}")
    L.append("")
    L.append("/-- Species of the model. -/")
    L.append(f"inductive Species | {' | '.join(sp)}")
    L.append("  deriving DecidableEq, Repr")
    L.append("")
    L.append("open Species")
    L.append("")
    L.append("/-- Rate constants. -/")
    L.append("structure Params where")
    for p in model.params:
        L.append(f"  {user(p.name)} : ℝ")
    L.append("")
    L.append("/-- Interval assumptions over the parameters (confidence-graded "
             "in BSL). -/")
    L.append(f"structure Params.Valid ({P} : Params) : Prop where")
    for p in model.params:
        L.append(f"  {user(p.name + '_lo')} : {_fmt(p.lo)} ≤ {P}.{user(p.name)}"
                 f"    -- {p.grade}")
        L.append(f"  {user(p.name + '_hi')} : {P}.{user(p.name)} ≤ {_fmt(p.hi)}")
    L.append("")
    L.append("/-- Mass-action vector field  dX/dt. -/")
    L.append(f"def dXdt ({P} : Params) ({X} : Species → ℝ) : Species → ℝ")
    for s in model.species:
        L.append(f"  | {user(s.name)} => {_dxdt_rhs(model, s.name)}")
    L.append("")
    for inv in model.invariants:
        lhs = " + ".join(
            (f"dXdt {P} {X} {user(ref.species)}" if ref.coeff == 1.0
             else f"{_fmt(ref.coeff)} * dXdt {P} {X} {user(ref.species)}")
            for ref in inv.terms
        )
        expr = " + ".join(
            (ref.species if ref.coeff == 1.0 else f"{_fmt(ref.coeff)}*{ref.species}")
            for ref in inv.terms
        )
        L.append(f"/-- Conservation: BSL invariant `{inv.name}` states "
                 f"{expr} = {_fmt(inv.rhs)};")
        L.append(f"    equivalently d/dt({expr}) = 0. -/")
        L.append(f"theorem {user(inv.name)} ({P} : Params) ({X} : Species → ℝ) :")
        L.append(f"    {lhs} = 0 := by")
        L.append("  simp only [dXdt]")
        L.append("  ring")
        L.append("")
    L.append(f"end {ns}")
    L.append("")
    return "\n".join(L)
